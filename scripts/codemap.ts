// Generates .claude/codemap.md: every tracked file grouped by folder, with its line count and purpose.
// Purpose = first sentence of the file's leading comment; a Markdown file without one gives its first heading.
// Usage: npm run codemap (also runs in .husky/pre-commit; CI fails if the committed file is stale).
// Reads files as staged in the git index, not the working tree, so the map matches what gets committed.

import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { basename, dirname } from 'node:path';

export interface Entry {
  path: string;
  lines: number;
  purpose: string;
}

export const OUT = '.claude/codemap.md';
const SKIP = /(^|\/)(package-lock\.json|pnpm-lock\.yaml|yarn\.lock)$|^\.claude\/codemap\.md$/;
const BINARY =
  /\.(pdf|zip|gz|png|jpe?g|gif|webp|ico|svg|woff2?|ttf|otf|mp3|mp4|wav|webm|apk|aab|jar|keystore|jks)$/i;
const MAX = 140;

// Lines that may precede a file's purpose comment: shebang, directives, encodings, doctype.
const PREAMBLE =
  /^(#!|['"]use (strict|client|server)['"];?$|# -\*-|<\?php|<!doctype|# ?(syntax|escape|check)=|\/\/ ?@ts-|\/\/\/ ?<reference)/i;
// Leading comment markers of the languages we may use; JSON and friends have none.
const COMMENT = /^(\/\/\/?|\/\*+|\*\/?|#|--|<!--)\s?/;

/** The text cut to MAX characters, ending with an ellipsis when cut. */
const clip = (s: string): string => (s.length > MAX ? `${s.slice(0, MAX - 3).trimEnd()}...` : s);
/** The text up to its first sentence end, or all of it when it has none. */
const firstSentence = (s: string): string => s.match(/^.*?[.!?](?=\s|$)/)?.[0] ?? s;

/** Purpose of a file from its text: first sentence of the leading comment, else a Markdown file's first heading; '' if none. */
export function purpose(path: string, text: string): string {
  const lines = text.split(/\r?\n/).map((l) => l.trim());
  const opensWithComment = lines.find((l) => l !== '')?.startsWith('<!--') ?? false;
  if (/\.mdx?$/i.test(path) && !opensWithComment) {
    const heading = lines.find((l) => /^#{1,6}\s/.test(l));
    return heading ? clip(heading.replace(/^#+\s*/, '')) : '';
  }
  let i = 0;
  while (i < lines.length && (lines[i] === '' || PREAMBLE.test(lines[i] ?? ''))) i++;
  const first = lines[i] ?? '';
  const docstring = first.match(/^(?:"""|''')(.*)/);
  if (docstring)
    return clip(firstSentence((docstring[1] ?? '').replace(/("""|''').*$/, '').trim()));
  if (!COMMENT.test(first)) return '';
  const words: string[] = [];
  for (let line = lines[i]; line !== undefined && COMMENT.test(line); line = lines[++i]) {
    const body = line
      .replace(COMMENT, '')
      .replace(/\*\/$|--!?>$/, '')
      .trim();
    if (body) words.push(body);
    else if (words.length) break; // a bare `/**` opens the comment; a blank comment line ends the sentence
  }
  return clip(firstSentence(words.join(' ')));
}

/** Locale-independent order: the same map on every machine and in CI, whatever LANG is. */
const byCodeUnit = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);

/** Markdown of the code map, grouped by folder, root first. */
export function render(entries: Entry[]): string {
  const byDir = new Map<string, Entry[]>();
  for (const e of entries.toSorted((a, b) => byCodeUnit(a.path, b.path))) {
    const dir = dirname(e.path);
    byDir.set(dir, [...(byDir.get(dir) ?? []), e]);
  }
  const dirs = [...byDir.keys()].toSorted((a, b) =>
    a === '.' ? -1 : b === '.' ? 1 : byCodeUnit(a, b),
  );
  const out = [
    '# Code map',
    '',
    'Generated by `npm run codemap` (the pre-commit hook keeps it fresh, CI checks it). Do not edit by hand.',
    'Per file: line count and purpose (first sentence of the leading comment, else the first Markdown heading). Reads the git index: `git add` changes first.',
  ];
  for (const dir of dirs) {
    const files = byDir.get(dir) ?? [];
    const bare = files.filter((f) => !f.purpose).map((f) => `\`${basename(f.path)}\``);
    out.push('', `## ${dir === '.' ? '(root)' : dir}`, '');
    for (const f of files.filter((f) => f.purpose)) {
      out.push(`- \`${basename(f.path)}\` (${f.lines}): ${f.purpose}`);
    }
    if (bare.length) out.push(`- Also: ${bare.join(', ')}`);
  }
  return `${out.join('\n')}\n`;
}

/** Entries of `git ls-files -z -s` output, submodules left out. */
export function parseIndex(out: string): { path: string; sha: string }[] {
  return out
    .split('\0')
    .filter(Boolean)
    .flatMap((line) => {
      const [meta = '', path = ''] = line.split('\t');
      const [mode, sha = ''] = meta.split(' ');
      return mode === '160000' ? [] : [{ path, sha }];
    });
}

/** Blob contents by sha from `git cat-file --batch` output. */
export function parseBatch(buf: Buffer): Map<string, string> {
  const blobs = new Map<string, string>();
  let i = 0;
  while (i < buf.length) {
    const eol = buf.indexOf(10, i);
    const [sha = '', type, size] = buf.subarray(i, eol).toString().split(' ');
    if (type === 'missing') {
      i = eol + 1;
      continue;
    }
    const start = eol + 1;
    const end = start + Number(size);
    blobs.set(sha, buf.subarray(start, end).toString('utf8'));
    i = end + 1; // each blob is followed by a newline
  }
  return blobs;
}

/** Lines in a file's text: a trailing newline ends the last line, an empty file has none. */
export function lineCount(content: string): number {
  if (content === '') return 0;
  return content.split('\n').length - (content.endsWith('\n') ? 1 : 0);
}

/** Writes the code map of the files staged in the git index. */
function main(): void {
  const index = parseIndex(execFileSync('git', ['ls-files', '-z', '-s'], { encoding: 'utf8' }));
  const files = index.filter((e) => !SKIP.test(e.path));
  const text = files.filter((e) => !BINARY.test(e.path));
  const blobs = text.length
    ? parseBatch(
        execFileSync('git', ['cat-file', '--batch'], {
          input: `${text.map((e) => e.sha).join('\n')}\n`,
          maxBuffer: 1024 ** 3,
        }),
      )
    : new Map<string, string>();
  const entries = files.map(({ path, sha }): Entry => {
    const content = blobs.get(sha);
    if (content === undefined) return { path, lines: 0, purpose: '' };
    return {
      path,
      lines: lineCount(content),
      purpose: purpose(path, content),
    };
  });
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, render(entries));
  console.log(`Wrote ${OUT} (${entries.length} files).`);
}

if (import.meta.main) main();
